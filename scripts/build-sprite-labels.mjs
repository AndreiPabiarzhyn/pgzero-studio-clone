function replaceLongestFirst(text, dict) {
  let out = text;
  const keys = Object.keys(dict).sort((a, b) => b.length - a.length);
  keys.forEach(function (key) {
    out = out.split(key).join(dict[key]);
  });
  return out;
}

function buildMap(dict) {
  const map = {};
  sprites.forEach(function (entry) {
    map[entry.id] = replaceLongestFirst(entry.label, dict);
  });
  return map;
}

const enMap = buildMap(EN);
const esMap = {};
sprites.forEach(function (entry) {
  esMap[entry.id] = replaceLongestFirst(enMap[entry.id], ES);
});

